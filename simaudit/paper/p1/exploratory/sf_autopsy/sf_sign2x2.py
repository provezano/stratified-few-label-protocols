"""2x2 sign table at one label per class on the second frame (EXPLORATORY; post hoc).

Review 8 m2. Cross-tabulates, over the binary second-frame table x FM pairs at m = 1, the
necessary condition of the sign remark (stratified macro-F1 below the constant-majority value
p/(1+p), with p the pool majority share as in sf_autopsy.py Q3b) against the sign of the gap.
Uses sf_autopsy.py's loaders and estimator; second frame only (no HELD-OUT input).

Run from simaudit/:
  nice -n 15 .venv/bin/python paper/p1/exploratory/sf_autopsy/sf_sign2x2.py
"""

from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import sf_autopsy as sa  # noqa: E402

FMNAME = {"fm1": "TabPFN v2", "fm2": "TabICLv2", "fm3": "Kumo-Tabular", "fm5": "TabPFN v3.5"}


def main() -> None:
    tr = sa.traits()
    tr = tr[(tr.set == "sf") & (tr.binary == 1)]
    runs = sa.load_set("sf")
    sm = (runs[(runs.strategy == "stratified") & (runs.mult == 1)]
          .groupby(["set", "dataset", "learner"]).macro_f1.mean().rename("mS").reset_index())
    sm = sm.merge(tr[["set", "dataset", "pi_min"]], on=["set", "dataset"])
    pmaj = 1 - sm.pi_min
    sm["below"] = sm.mS < pmaj / (1 + pmaj)
    g1 = sa.table_gaps(runs, "macro_f1", (1,)).melt(id_vars=["set", "dataset"], var_name="learner", value_name="gap1")
    d = sm.merge(g1, on=["set", "dataset", "learner"])
    d["neg"] = d.gap1 < 0
    cells = {
        "BelowNeg": int((d.below & d.neg).sum()),
        "BelowNonNeg": int((d.below & ~d.neg).sum()),
        "AboveNeg": int((~d.below & d.neg).sum()),
        "AboveNonNeg": int((~d.below & ~d.neg).sum()),
    }
    n = len(d)
    assert sum(cells.values()) == n
    viol = d[~d.below & d.neg]
    words = {0: "no", 1: "one", 2: "two", 3: "three", 4: "four", 5: "five"}
    lines = ["% AUTO-GENERATED by paper/p1/exploratory/sf_autopsy/sf_sign2x2.py. EXPLORATORY; post hoc. Do not edit."]

    def put(name: str, value: str, what: str) -> None:
        lines.append(f"\\newcommand{{\\ExSFASign{name}}}{{{value}}} % EXPLORATORY; post hoc; {what}")

    put("N", str(n), "second frame binary table x FM pairs at m=1")
    for k, v in cells.items():
        put(k, str(v), f"pairs: condition {'met' if k.startswith('Below') else 'not met'}, gap {'< 0' if k.endswith('Neg') and 'Non' not in k else '>= 0'}")
        put(k + "Word", words.get(v, str(v)), "same count in words")
    if len(viol) == 1:
        r = viol.iloc[0]
        put("ViolGap", f"${r.gap1:+.3f}$", "gap of the one pair with a negative gap that does not meet the condition")
        put("ViolFM", FMNAME[r.learner], "FM of that pair")
    (HERE / "sf_sign2x2_numbers.tex").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    print(viol[["dataset", "learner", "mS", "gap1"]])
    print(d[d.below & ~d.neg][["dataset", "learner"]])


if __name__ == "__main__":
    main()
