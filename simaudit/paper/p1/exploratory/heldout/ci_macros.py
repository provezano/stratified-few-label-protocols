"""HELD-OUT CI and cross-study p macros read from the joint analysis output.

Reads results/joint/heldout/joint_results.json (written once by
simaudit.analysis.joint_heldout at the joint opening; no fits, no new tests)
and writes out/heldout_ci_numbers.tex with:

- the bootstrap 95% CI of each Study 13 confirmatory contrast (i)-fmX and
  (ii-a): \\HOI<FM>Lo/Hi, \\HOIIaLo/Hi ((ii-c) already has \\HOIIcLo/Hi);
- the within-study and cross-study Holm p of every Study 9 HELD-OUT test:
  \\HOSnineXHolmHThreeb and \\HOSnineOtherPList (the seven tests not supported
  on PMLB/UCI, "Holm p [cross-study Holm p]").

Formatting reuses fmt_num/fmt_p of joint_heldout, so the numbers match
heldout_numbers.tex.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd

from simaudit.analysis.joint_heldout import FM_WORD, fmt_num, fmt_p
from simaudit.settings import settings

HERE = Path(__file__).resolve().parent
OUT = HERE / "out"

S9_OTHER = {
    "H1b": "H1b",
    "H2a|kmedoids_nested": "H2a (k-medoids)",
    "H2a|lucos_nested": "H2a (LUCoS)",
    "H2b|kmedoids_nested": "H2b (k-medoids)",
    "H2b|lucos_nested": "H2b (LUCoS)",
    "H4|agree": "H4 (agreement)",
    "H4|fm_disagree": "H4 (FM disagreement)",
}


def frame(block: dict) -> pd.DataFrame:
    """A pandas 'split' dict back to a DataFrame."""
    return pd.DataFrame(block["data"], columns=block["columns"])


def macros(res: dict) -> dict[str, str]:
    """All macros of this file, from the parsed joint_results.json."""
    conf = frame(res["study13"]["confirmatory"]).set_index("id")
    m: dict[str, str] = {}
    for fm, word in FM_WORD.items():
        row = conf.loc[f"(i)-{fm}"]
        m[f"HOI{word}Lo"] = fmt_num(row["ci_low"])
        m[f"HOI{word}Hi"] = fmt_num(row["ci_high"])
    m["HOIIaLo"] = fmt_num(conf.loc["(ii-a)", "ci_low"])
    m["HOIIaHi"] = fmt_num(conf.loc["(ii-a)", "ci_high"])
    joint = frame(res["joint"])
    s9 = joint[joint.study == "study9"].set_index("test")
    m["HOSnineXHolmHThreeb"] = fmt_p(s9.loc["H3b", "p_holm_cross"])
    parts = [
        f"{name} {fmt_p(s9.loc[t, 'p_holm_within'])} [{fmt_p(s9.loc[t, 'p_holm_cross'])}]"
        for t, name in S9_OTHER.items()
    ]
    m["HOSnineOtherPList"] = "; ".join(parts)
    return m


def write(m: dict[str, str], path: Path, src: Path) -> None:
    lines = [
        "% Generated by exploratory/heldout/ci_macros.py; do not edit by hand.",
        f"% source: {src.name} (generated {json.loads(src.read_text())['generated']})",
        *(f"\\def\\{k}{{{v}}}%" for k, v in sorted(m.items())),
    ]
    path.write_text("\n".join(lines) + "\n")


def main(argv: list[str]) -> None:
    src = Path(argv[1]) if len(argv) > 1 else settings.results_dir / "joint" / "heldout" / "joint_results.json"
    out = Path(argv[2]) if len(argv) > 2 else OUT / "heldout_ci_numbers.tex"
    out.parent.mkdir(exist_ok=True)
    write(macros(json.loads(src.read_text())), out, src)
    print(out.read_text())


if __name__ == "__main__":
    main(sys.argv)
