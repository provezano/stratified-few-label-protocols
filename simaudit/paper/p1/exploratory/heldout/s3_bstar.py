"""HELD-OUT S-3 (pre-declared, descriptive): binary B* sign agreement.

prereg/STUDY13_HELDOUT_CONFIRMATION.md S-3: on binary tables, the share of
(table, FM, m) cells with |dA| > 0.01 whose sign of dA (stratified - random
accuracy, arm T) agrees with the Prop. 2(ii) threshold, sign(B* - B), with
B* = 1/(pi1 pi2 tau*^2) and tau* = log(pi2/pi1) from the full table's class
shares, as in ../e6_accuracy_heterogeneity.py (whose cell logic and threshold()
are reused here). Reads the stored Study 13 HELD-OUT outputs; no fits.

Writes out/s3_bstar_cells.csv, out/s3_bstar_threshold.csv and
out/heldout_s3_numbers.tex (\\HOSThreeBstarAgree).
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

for _v in ("OMP_NUM_THREADS", "OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS"):
    os.environ.setdefault(_v, "1")

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

import common as cm  # noqa: E402
import e6_accuracy_heterogeneity as e6  # noqa: E402
from simaudit.analysis import study12 as a12  # noqa: E402
from simaudit.analysis import study13 as a13  # noqa: E402
from simaudit.settings import settings  # noqa: E402

OUT = HERE / "out"


def cells(runs: pd.DataFrame, tables: pd.DataFrame) -> pd.DataFrame:
    """One row per (table, FM, m): dA and the binary threshold B*, as in e6.cells()."""
    counts = tables.set_index("key")["class_counts"].map(lambda s: [int(c) for c in str(s).split(";")])
    means = a12.cell_means(a13.arm(runs, "T"), "accuracy")
    rows = []
    for (did, fm, m), g in means[means.learner.isin(cm.FMS)].groupby(["dataset", "learner", "mult"]):
        s = g.set_index("strategy")["accuracy"]
        if not {"stratified", "random"} <= set(s.index) or did not in counts.index:
            continue
        c = counts[did]
        rows.append(dict(dataset=did, fm=fm, mult=int(m), C=len(c), B=int(m) * len(c),
                         pi_min=min(c) / sum(c), dA=float(s["stratified"] - s["random"])))
    out = pd.DataFrame(rows)
    pi1 = out.pi_min
    tau = np.log((1 - pi1) / pi1)
    with np.errstate(divide="ignore"):
        out["B_star"] = np.where(out.C == 2, 1 / (pi1 * (1 - pi1) * tau**2), np.nan)
    return out


def main() -> None:
    OUT.mkdir(exist_ok=True)
    root = settings.results_dir / "study13" / "heldout"
    runs = a13.load_runs(root)
    tables = pd.read_csv(root / "integrity_screen.csv")
    c = cells(runs, tables)
    c.to_csv(OUT / "s3_bstar_cells.csv", index=False)
    th = e6.threshold(c)
    th.to_csv(OUT / "s3_bstar_threshold.csv", index=False)
    row = th[th.fm == "all"].iloc[0]
    agree = f"{100 * row.agree:.0f}\\%"
    (OUT / "heldout_s3_numbers.tex").write_text(
        "% AUTO-GENERATED by paper/p1/exploratory/heldout/s3_bstar.py (HELD-OUT S-3, pre-declared, descriptive). Do not edit.\n"
        f"\\newcommand{{\\HOSThreeBstarAgree}}{{{agree}}} % share of {int(row.n_decisive)} decisive binary cells\n"
        f"\\newcommand{{\\HOSThreeBstarNDecisive}}{{{int(row.n_decisive)}}}\n"
    )
    print(th.round(3).to_string(index=False))


if __name__ == "__main__":
    main()
