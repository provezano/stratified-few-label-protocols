"""HELD-OUT gap at three to ten labels per class (EXPLORATORY, post hoc; stored outputs only, no fits).

Same estimator, unit and interval as the DEV and PMLB/UCI "S-R, m >= 3" column of Table 2
(../review_reanalysis/r17_did.py, reused here): per table, the mean over repetitions of
stratified - random macro-F1 at m in {3, 5, 10}, averaged over these budgets; mean over tables,
percentile bootstrap 95% CI over tables (10,000 resamples, seed 20261030), two-sided Wilcoxon
signed-rank p (unadjusted). Input: the Study 13 HELD-OUT outputs, arm T (the arm of the
confirmatory contrasts), four pre-registered FMs.

Writes out/heldout_m3plus_numbers.tex (\\ExHOGapNoOne...) and out/heldout_m3plus.csv.
Run from simaudit/: nice -n 15 .venv/bin/python paper/p1/exploratory/heldout/m3plus.py
"""

from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "review_reanalysis"))

import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402
import pyarrow.parquet as pq  # noqa: E402

import r17_did  # noqa: E402
from rv_common import FMS, FMW, fmt, pfmt  # noqa: E402

OUT = HERE / "out"
SRC = "results/study13/heldout (arm T, metric columns), m3plus.py"


def load_heldout(folder: Path) -> pd.DataFrame:
    """Arm-T cell means in the layout of r17_did.load(): index (dataset, learner, mult), columns = strategy."""
    parts = []
    for fm in FMS:
        for f in sorted(folder.glob(f"*_{fm}.parquet")):
            t = pq.read_table(f, columns=["arm", *r17_did.COLS]).to_pandas()
            parts.append(t[(t.arm == "T") & t.strategy.isin(["stratified", "random"])].drop(columns="arm"))
    d = pd.concat(parts)
    d["dataset"] = d.dataset.astype(str)
    return d.groupby(["dataset", "learner", "strategy", "mult"]).macro_f1.mean().unstack("strategy")


def main() -> None:
    g = load_heldout(r17_did.REPO / "results" / "study13" / "heldout")
    gen = np.random.default_rng(20261030)
    rows, lines = [], [
        "% AUTO-GENERATED by paper/p1/exploratory/heldout/m3plus.py. EXPLORATORY (post hoc). Do not edit."
    ]

    def put(name: str, value: str, what: str) -> None:
        lines.append(f"\\newcommand{{\\ExHOGapNoOne{name}}}{{{value}}} % EXPLORATORY; source: {SRC} ({what})")

    for fm in FMS:
        x = r17_did.gap_m3to10(g, fm)
        m, lo, hi, p = r17_did.summary(x, gen)
        rows.append(dict(fm=fm, n=len(x), mean=m, lo=lo, hi=hi, p=p))
        w = FMW[fm]
        put(w, fmt(m, sign=True), f"{fm}, S-R mean over m=3,5,10, mean over tables")
        put(f"{w}Lo", fmt(lo, sign=True), f"{fm}, bootstrap 2.5%")
        put(f"{w}Hi", fmt(hi, sign=True), f"{fm}, bootstrap 97.5%")
        put(f"{w}P", pfmt(p), f"{fm}, two-sided Wilcoxon, unadjusted")
    r = pd.DataFrame(rows)
    put("Min", fmt(r["mean"].min(), sign=True), "min over 4 FMs")
    put("Max", fmt(r["mean"].max(), sign=True), "max over 4 FMs")
    put("LoMin", fmt(r.lo.min(), sign=True), "smallest bootstrap 2.5% over 4 FMs")
    put("HiMax", fmt(r.hi.max(), sign=True), "largest bootstrap 97.5% over 4 FMs")
    put("PMax", pfmt(r.p.max()), "largest unadjusted Wilcoxon p over 4 FMs")
    put("N", str(int(r.n.min())), "tables")
    OUT.mkdir(exist_ok=True)
    r.to_csv(OUT / "heldout_m3plus.csv", index=False)
    (OUT / "heldout_m3plus_numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(r.round(4).to_string(index=False))


if __name__ == "__main__":
    main()
