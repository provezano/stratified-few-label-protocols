"""EXPLORATORY summary of the Kumo declared-but-unused class test (PLAN.md, commit R023).

Reads out/runs/*.parquet (run_kumo_unused.py). Writes out/summary.csv, out/SUMMARY.md and
out/kumo_unused_numbers.tex (prefix ExKumoUnused; every macro EXPLORATORY).
Usage: PYTHONPATH=src .venv/bin/python paper/p1/exploratory/kumo_unused/summarize.py
"""

from __future__ import annotations

from pathlib import Path


import pandas as pd

HERE = Path(__file__).resolve().parent
OUT = HERE / "out"
SRC = "kumo_unused/out/summary.csv (EXPLORATORY; DEV, Study 7 Part (a) random draws that missed a class)"


def main() -> None:
    cols = ["dataset", "mult", "rep", "n_classes", "n_seen", "arm", "error", "n_returned",
            "max_abs_diff_stored", "macro_f1", "absent_mass", "absent_max", "absent_argmax_share",
            "absent_f1", "absent_f1_random"]
    df = pd.concat([pd.read_parquet(p) for p in sorted((OUT / "runs").glob("*.parquet"))])
    df = df[[c for c in cols if c in df.columns]]
    df["multiclass"] = df.n_classes > 2
    dec, std = df[df.arm == "decl"], df[df.arm == "std"]
    key = ["dataset", "mult", "rep"]
    m = dec.merge(std[key + ["macro_f1", "max_abs_diff_stored"]], on=key, suffixes=("", "_std"))
    rows = []
    for name, g in (("all", m), ("multiclass", m[m.multiclass]), ("binary one-class", m[~m.multiclass])):
        rows.append(dict(
            subset=name, draws=len(g), tables=g.dataset.nunique(),
            errors=int((g.error.fillna("") != "").sum()),
            draws_absent_col_returned=int((g.n_returned > g.n_seen).sum()),
            max_absent_mass=float(g.absent_mass.max()), max_absent_argmax_share=float(g.absent_argmax_share.max()),
            max_abs_decl_minus_stored=float(g.max_abs_diff_stored.max()),
            max_abs_std_minus_stored=float(g.max_abs_diff_stored_std.max()),
            max_abs_macro_f1_decl_minus_std=float((g.macro_f1 - g.macro_f1_std).abs().max()),
            mean_absent_f1=float(g.absent_f1.mean()),
        ))
    s = pd.DataFrame(rows)
    s.to_csv(OUT / "summary.csv", index=False)
    a = s.iloc[0]
    never = (a.draws_absent_col_returned == 0 and a.max_absent_mass == 0 and a.max_absent_argmax_share == 0
             and a.max_abs_decl_minus_stored <= 1e-6 and a.errors == 0)
    verdict = "never predicts (declared unused classes dropped)" if never else "see table (not 'never')"
    L = ["# EXPLORATORY: Kumo-Tabular with declared but unused classes (DEV; PLAN.md)", "",
         f"Verdict by the pre-set rule: **{verdict}**.", "",
         s.to_markdown(index=False), "",
         "decl = label column declared over all C classes (pd.Categorical); std = paper path re-run; "
         "stored = Study 7 Part (a). Columns not returned are set to 0."]
    (OUT / "SUMMARY.md").write_text("\n".join(L) + "\n")
    mc, b = s.iloc[1], s.iloc[2]

    def e(x: float) -> str:
        if x == 0:
            return "0"
        mant, ex = f"{x:.1e}".split("e")
        return f"${mant}\\times10^{{{int(ex)}}}$"

    mac = {
        "ExKumoUnusedDraws": (str(int(a.draws)), ""),
        "ExKumoUnusedTables": (str(int(a.tables)), ""),
        "ExKumoUnusedMultiDraws": (str(int(mc.draws)), "; multiclass tables"),
        "ExKumoUnusedMultiTables": (str(int(mc.tables)), "; multiclass tables"),
        "ExKumoUnusedOneClassDraws": (str(int(b.draws)), "; one-class contexts on binary tables"),
        "ExKumoUnusedAbsentReturned": (str(int(a.draws_absent_col_returned)), "; draws where Kumo returned an absent-class column"),
        "ExKumoUnusedMaxAbsentMass": (e(a.max_absent_mass), "; max mean probability on absent classes"),
        "ExKumoUnusedMaxAbsDiff": (e(a.max_abs_decl_minus_stored), "; max |declared - stored| probability"),
        "ExKumoUnusedVerdict": ("never" if never else "not never", "; pre-set reading of PLAN.md"),
    }
    lines = ["% Generated by paper/p1/exploratory/kumo_unused/summarize.py. Do not edit.",
             "% EXPLORATORY (not pre-registered; plan R023): Kumo-Tabular with declared but unused classes, DEV."]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}} % {SRC}{c}" for k, (v, c) in sorted(mac.items())]
    (OUT / "kumo_unused_numbers.tex").write_text("\n".join(lines) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
