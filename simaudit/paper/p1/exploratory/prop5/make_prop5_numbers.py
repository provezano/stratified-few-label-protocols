"""Numbers for Prop. 5(iii) (prop:prior) of P1. EXPLORATORY theory check, no data.

Two Gaussian classes N(0,1), N(d,1), pool law known. Computes
- the separation d below which stratified labels + an infinite pool have a larger
  asymptotic variance bound V_S than the label frequency of B random labels (pi1pi2),
  for pi1 in {0.5, 0.3, 0.1}; reported rounded DOWN to one decimal (safe side);
- V_S / Omega at pi1 = 0.1, d = 4.
Writes out/prop5_numbers.tex. Scripts copied from the proposal (bounds.py, cross.py,
mc.py, mc_small.py) and the independent check (verify.py).
"""
import math, pathlib
from scipy.optimize import brentq
from bounds import quantities

def cross(pi1):
    return brentq(lambda d: quantities(pi1, d)[3] - quantities(pi1, d)[5], 0.3, 4)

ds = {p: cross(p) for p in (0.5, 0.3, 0.1)}
lo = math.floor(min(ds.values()) * 10) / 10
hi = math.floor(max(ds.values()) * 10) / 10
Om, G, KG, VS, VR, pp = quantities(0.1, 4)
ratio = VS / Om
out = pathlib.Path(__file__).parent / "out" / "prop5_numbers.tex"
out.write_text(
    "% Generated by exploratory/prop5/make_prop5_numbers.py; do not edit. Theory check (no data).\n"
    f"\\newcommand{{\\ThPriorCrossDLo}}{{{lo:.1f}}} % min over pi1 in {{0.5,0.3,0.1}} of crossover d (V_S = pi1 pi2), floored; raw {', '.join(f'{k}: {v:.3f}' for k, v in ds.items())}\n"
    f"\\newcommand{{\\ThPriorCrossDHi}}{{{hi:.1f}}} % max of the same crossovers, floored\n"
    f"\\newcommand{{\\ThPriorRatioSep}}{{{ratio:.2f}}} % V_S / Omega at pi1 = 0.1, d = 4 (raw {ratio:.4f})\n")
print(out.read_text())
