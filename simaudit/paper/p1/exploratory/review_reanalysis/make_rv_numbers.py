import re

from rv_common import OUT

head = ["% Blind-review re-analyses of stored outputs. EVERY macro here is EXPLORATORY unless its",
        "% source comment names a pre-registered or pre-declared provenance. Generated by make_rv_numbers.py.",
        "% Part (a) depends on the coding file named in out/a_subtypes.csv; re-run after adjudication."]
lines = []
for part in ("a", "bc", "s9", "ten", "mech", "accdose", "r4", "r5", "r6", "r6b", "r7fs", "r7", "r8", "r10", "r11", "r12", "r13", "r14", "r15", "r16", "r17", "r18", "r19"):
    lines += (OUT / f"rv_{part}.tex").read_text(encoding="utf-8").splitlines()
names = [re.match(r"\\newcommand\{\\(\w+)\}", ln).group(1) for ln in lines]
dup = {n for n in names if names.count(n) > 1}
assert not dup, dup
(OUT / "rv_numbers.tex").write_text("\n".join(head + sorted(lines)) + "\n", encoding="utf-8")
print(len(lines), "macros")
