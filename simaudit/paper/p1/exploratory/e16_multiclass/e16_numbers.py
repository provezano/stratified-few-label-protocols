"""E16 step 5: quotable numbers as LaTeX macros (exploratory).

Reads e16_multiclass/out/e16_*.csv (and the merge CSVs when present) and writes
paper/p1/exploratory/out/e16_numbers.tex; every macro carries its source in a comment.

Run from simaudit/: .venv/bin/python paper/p1/exploratory/e16_multiclass/e16_numbers.py
"""

