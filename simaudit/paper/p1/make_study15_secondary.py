"""Write study15_secondary_numbers.tex from the stored Study 15 results.

Reads results/study15/study15_results.json (the single pre-registered run) and
formats the pre-declared secondary values that the analysis did not emit as
macros. Nothing is recomputed.

    .venv/bin/python paper/p1/make_study15_secondary.py
"""

from __future__ import annotations

import json
from pathlib import Path

from simaudit.analysis.study15 import fmt_num, fmt_p

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "results/study15/study15_results.json"
OUT = Path(__file__).with_name("study15_secondary_numbers.tex")
NAME = {"fm1": "One", "fm2": "Two", "fm3": "Three", "fm5": "Five"}
METRIC = {"accuracy": "Acc", "balanced_accuracy": "BA"}
BUDGET = {"1": "One", "3": "Three", "5": "Five", "10": "Ten"}
LEARNER = {
    "lr": "Lr", "knn1": "KnnOne", "knn3": "KnnThree",
    "gnb": "Gnb", "lda": "Lda", "hgb": "Hgb",
}


def main() -> None:
    res = json.loads(SRC.read_text())
    m: dict[str, str] = {}
    n_multi = len(res["exploratory_multiclass"]["tables"])
    m["SFNMulti"] = str(n_multi)
    m["SFNBinary"] = str(int(res["n_tables"]) - n_multi)
    for key, tag in METRIC.items():
        for fm, name in NAME.items():
            r = res[key][fm]
            m[f"SF{tag}FM{name}Mean"] = fmt_num(r["mean"])
            m[f"SF{tag}FM{name}CI"] = f"[{fmt_num(r['ci_low'])}, {fmt_num(r['ci_high'])}]"
            m[f"SF{tag}FM{name}P"] = fmt_p(r["p"])
    for fm, name in NAME.items():
        for budget, r in res["per_budget"][fm].items():
            m[f"SFBudgetFM{name}M{BUDGET[budget]}"] = fmt_num(r["mean"])
    for fm, name in NAME.items():
        for budget, r in res["per_budget"][fm].items():
            ci = f"[{fmt_num(r['ci_low'])}, {fmt_num(r['ci_high'])}]"
            m[f"SFBudgetFM{name}M{BUDGET[budget]}CI"] = ci
            m[f"SFBudgetFM{name}M{BUDGET[budget]}P"] = fmt_p(r["p"])
    cols = res["primary"]["columns"]
    for row in res["primary"]["data"]:
        r = dict(zip(cols, row))
        name = NAME[str(r["id"]).split("-")[1]]
        ratio = float(r["ratio_to_heldout"])
        heldout_mean = float(r["mean"]) / ratio
        inside = float(r["ci_low"]) <= heldout_mean <= float(r["ci_high"])
        m[f"SFRatioHoFM{name}"] = f"${ratio:.2f}$"
        m[f"SFHoInsideFM{name}"] = "yes" if inside else "no"
    m["SFHoInsideCount"] = str(
        sum(m[f"SFHoInsideFM{n}"] == "yes" for n in NAME.values()),
    )
    safe = res["exploratory_tabpfn35_safe"]["fm5"]
    m["SFSafeFiveCI"] = f"[{fmt_num(safe['ci_low'])}, {fmt_num(safe['ci_high'])}]"
    m["SFSafeFiveP"] = fmt_p(safe["p"])
    for key, tag in (("exploratory_binary", "Bin"), ("exploratory_multiclass", "Multi")):
        for fm, name in NAME.items():
            r = res[key][fm]
            m[f"SF{tag}FM{name}Mean"] = fmt_num(r["mean"])
            m[f"SF{tag}FM{name}CI"] = f"[{fmt_num(r['ci_low'])}, {fmt_num(r['ci_high'])}]"
    cols = res["s1_classical"]["columns"]
    rows = [dict(zip(cols, row)) for row in res["s1_classical"]["data"]]
    for r in rows:
        tag = LEARNER[str(r["learner"])]
        m[f"SFClassic{tag}Mean"] = fmt_num(r["mean"])
        m[f"SFClassic{tag}Holm"] = fmt_p(r["p_holm"])
    m["SFClassicNSig"] = str(sum(float(r["p_holm"]) < 0.05 for r in rows))
    m["SFClassicN"] = str(len(rows))
    means = [float(r["mean"]) for r in rows]
    m["SFClassicMin"] = fmt_num(min(means))
    m["SFClassicMax"] = fmt_num(max(means))
    for sens, tag in (("sens_int", "Int"), ("sens_id", "Id")):
        m[f"SFSens{tag}N"] = str(len(res[sens]["dropped"]))
        m[f"SFSens{tag}Verdict"] = res[sens]["claim"]["text"]
    head = [
        "% Generated by paper/p1/make_study15_secondary.py from the single Study 15 run;",
        "% pre-declared secondary values (unadjusted, no direction). Do not edit by hand.",
    ]
    lines = [f"\\def\\{k}{{{v}}}" for k, v in sorted(m.items())]
    OUT.write_text("\n".join(head + lines) + "\n")


if __name__ == "__main__":
    main()
