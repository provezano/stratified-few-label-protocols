"""Write seedindep_t1p_numbers.tex from the analyze/repro outputs of run_seed_indep_t1p.py. EXPLORATORY.

Reads (written by the driver, which this script never runs):
  out/summary_t1p.csv  (mode analyze: learner, metric, n_tables, gap_orig, gap_indep, diff, lo, hi, verdict, ...)
  out/repro_t1p.csv    (mode repro: learner, strategy, d_macro_f1, d_proba)
Writes paper/p1/seedindep_t1p_numbers.tex. main.tex inputs that file only if it exists (hook in the
preamble, \\ifseedtp), so the PMLB/UCI paragraph and the four table rows appear only after this script ran.
Format as paper/p1/exploratory/seed_indep/seed_indep_numbers.tex (DEV). Nothing is recomputed.

    .venv/bin/python paper/p1/rebuttal_prep/seed_indep_t1p/make_seedindep_t1p_numbers.py [--out-dir DIR] [--tex PATH]
"""
from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
NAME = {"fm1": "One", "fm2": "Two", "fm3": "Three", "fm5": "Five"}
VERDICTS = {"materially unchanged", "changed", "inconclusive"}


def sgn(x: float, digits: int) -> str:
    return f"{'$+$' if x >= 0 else '$-$'}{abs(x):.{digits}f}"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out-dir", type=Path, default=HERE / "out")
    ap.add_argument("--tex", type=Path, default=HERE.parents[1] / "seedindep_t1p_numbers.tex")
    a = ap.parse_args()
    s = pd.read_csv(a.out_dir / "summary_t1p.csv")
    s = s[s.metric == "macro_f1"].set_index("learner")
    missing = sorted(set(NAME) - set(s.index))
    assert not missing, f"summary_t1p.csv lacks macro_f1 rows for {missing}"
    rp = pd.read_csv(a.out_dir / "repro_t1p.csv")
    src = "source: rebuttal_prep/seed_indep_t1p/out/summary_t1p.csv (PMLB/UCI, {fm}, macro_f1)"
    lines = ["% AUTO-GENERATED by paper/p1/rebuttal_prep/seed_indep_t1p/make_seedindep_t1p_numbers.py. "
             "EXPLORATORY (independent learner seed on PMLB/UCI; plan and reading rule fixed before the run). "
             "Do not edit."]
    ends = []
    for fm, nm in NAME.items():
        r = s.loc[fm]
        v = str(r.verdict)
        assert v in VERDICTS, (fm, v)
        k = f"ExSeedIndTpFm{nm}"
        for suffix, val in (("GapOrig", sgn(r.gap_orig, 3)), ("GapIndep", sgn(r.gap_indep, 3)),
                            ("Diff", sgn(r["diff"], 4)), ("DiffLo", sgn(r.lo, 4)), ("DiffHi", sgn(r.hi, 4)),
                            ("Verdict", v), ("N", str(int(r.n_tables)))):
            lines.append(f"\\newcommand{{\\{k}{suffix}}}{{{val}}} % EXPLORATORY; {src.format(fm=fm)}")
        ends += [abs(r.lo), abs(r.hi)]
    n_unch = int(sum(s.loc[fm].verdict == "materially unchanged" for fm in NAME))
    lines.append(f"\\newcommand{{\\ExSeedIndTpNUnchanged}}{{{n_unch}}} % EXPLORATORY; FMs read as materially unchanged")
    lines.append(f"\\newcommand{{\\ExSeedIndTpMaxAbsDiffCI}}{{{max(ends):.4f}}} % EXPLORATORY; largest |CI end| over the four FMs")
    lines.append(f"\\newcommand{{\\ExSeedIndTpReproMax}}{{{rp.d_macro_f1.max():.4f}}} "
                 "% EXPLORATORY; source: out/repro_t1p.csv, largest |change| in macro-F1 with the original seed")
    a.tex.write_text("\n".join(lines) + "\n")
    print(f"wrote {a.tex}")


if __name__ == "__main__":
    main()
