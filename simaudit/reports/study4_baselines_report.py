"""Study 4 Amendment 3: every label-free selector vs random and vs LUCoS (DEV)."""

from pathlib import Path

import pandas as pd

from simaudit.analysis.study4 import tests_table
from simaudit.settings import settings

A = settings.results_dir / "study4_stage_a"
B = settings.results_dir / "study4_stage_b"
OUT = Path(__file__).with_name("STUDY4_BASELINES.md")
COLS = ["dataset", "mult", "strategy", "learner", "rep", "macro_f1", "accuracy"]
# The two references that read y are left out of the selector families.
USES_Y = {"stratified", "stratified_medoids"}
NEW = ("usl", "rdss", "zcore", "kmedoids_raw")
LEARNERS = ("fm2", "fm1", "fm5", "fm3")


def frames() -> pd.DataFrame:
    """Every FM row (not LLGC) of Stage A, Stage B and the added strategies."""
    paths = list(A.glob("*.parquet")) + list(B.glob("*.parquet"))
    df = pd.concat([pd.read_parquet(p, columns=COLS) for p in paths])
    df = df[~df.learner.str.startswith("llgc_") & ~df.strategy.isin(USES_Y)]
    n = df.groupby(["strategy", "learner"]).dataset.transform("nunique")
    return df[n == df.dataset.nunique()]


def against(df: pd.DataFrame, reference: str, metric: str) -> pd.DataFrame:
    """Δ vs the reference, Holm within (FM, budget) over the other selectors."""
    sub = df.copy()
    if reference != "random":
        sub = sub[sub.strategy != "random"]
        sub["strategy"] = sub.strategy.replace({reference: "random"})
    return tests_table(sub, metric)


def cell(row: pd.Series) -> str:
    """Mean Δ, Holm p and wins/n, bold when Holm p < 0.05."""
    text = f"{row.mean_delta:+.3f} (p={row.p_holm:.3f}, {row.wins}/{row.n})"
    return f"**{text}**" if row.p_holm < 0.05 else text


def per_learner(table: pd.DataFrame, learner: str) -> str:
    """One markdown table: strategies x budgets for one FM."""
    sub = table[table.learner == learner].copy()
    sub["cell"] = sub.apply(cell, axis=1)
    pivot = sub.pivot(index="strategy", columns="mult", values="cell")
    order = sub.groupby("strategy").mean_delta.mean().sort_values(ascending=False)
    return str(pivot.loc[order.index].to_markdown())


def summary(table: pd.DataFrame) -> str:
    """Mean Δ over the four FMs and the number of FMs with Holm p < 0.05."""
    table = table.assign(
        up=(table.p_holm < 0.05) & (table.mean_delta > 0),
        down=(table.p_holm < 0.05) & (table.mean_delta < 0),
    )
    frame = (
        table.groupby(["strategy", "mult"])
        .agg(mean=("mean_delta", "mean"), sig_up=("up", "sum"), sig_down=("down", "sum"))
        .reset_index()
    )
    frame["cell"] = frame.apply(
        lambda r: f"{r['mean']:+.3f} ({r.sig_up}↑ {r.sig_down}↓)", axis=1
    )
    pivot = frame.pivot(index="strategy", columns="mult", values="cell")
    order = frame.groupby("strategy")["mean"].mean().sort_values(ascending=False)
    return str(pivot.loc[order.index].to_markdown())


def main() -> None:
    """Write STUDY4_BASELINES.md."""
    df = frames()
    have = set(zip(df.strategy, df.learner))
    missing = [f"{s}/{fm}" for s in NEW for fm in LEARNERS if (s, fm) not in have]
    parts = [
        "# Study 4, Amendments 3–4: USL, RDSS, ZCore and raw k-medoids against every selector (DEV)",
        "",
        "Generated by `reports/study4_baselines_report.py`. 20 DEV datasets, "
        "the dataset is the unit (mean over repetitions); FM learners only. "
        "Label-free selectors only (the references that read y are left out). "
        "Holm within FM × budget over the selectors compared with the same "
        "reference; bold = Holm p < 0.05. Exploratory throughout.",
        "",
    ]
    if missing:
        parts += [f"Not yet complete, left out: {', '.join(missing)}.", ""]
    for reference in ("random", "lucos"):
        for metric in ("macro_f1", "accuracy"):
            table = against(df, reference, metric)
            parts += [
                f"## Selector − {reference}, {metric}: mean over the four FMs",
                "",
                "Cells: mean Δ over FMs (number of FMs with Holm p < 0.05, "
                "up / down).",
                "",
                summary(table),
                "",
            ]
            for learner in LEARNERS:
                parts += [
                    f"### Selector − {reference}, {metric}, {learner}",
                    "",
                    "Cells: mean Δ (Holm p, wins/n).",
                    "",
                    per_learner(table, learner),
                    "",
                ]
    previous = OUT.read_text() if OUT.exists() else ""
    reading = previous[previous.find("## Reading") :] if "## Reading" in previous else ""
    OUT.write_text("\n".join(parts) + ("\n" + reading if reading else ""))
    print("\n".join(parts))


if __name__ == "__main__":
    main()
