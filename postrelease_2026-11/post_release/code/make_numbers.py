"""LaTeX macros for the paper from results/RESULTS.json (fresh-table confirmation). Writes
papers/p1_dmkd/confirm_numbers.tex. Prefix \\Fr (fresh)."""
import json
from pathlib import Path

BASE = Path(__file__).resolve().parents[1]
R = json.loads((BASE / "results/RESULTS.json").read_text())
FM = dict(fm1="One", fm2="Two", fm3="Three", fm5="Five")
out = []


def m(name, val):
    out.append(f"\\newcommand{{\\{name}}}{{{val}}}")


def s(x, d=3):
    return f"{x:+.{d}f}".replace("-", "$-$") if x < 0 else f"{x:+.{d}f}"


def ci(c, d=3):
    return f"[{s(c[0], d)}, {s(c[1], d)}]"


def p(x):
    return "<0.001" if x < 0.001 else f"{x:.3f}"


m("FrNTables", R["n_tables"])
m("FrNImb", R["n_imbalanced"])
h = R["H-pred"]
m("FrPredRho", f"{h['rho']:.2f}")
m("FrPredP", p(R["tests"]["H-pred"]["p_adj"]))
m("FrPredSlope", f"{h['slope']:.2f}")
m("FrPredSlopeCI", f"[{h['slope_ci'][0]:.2f}, {h['slope_ci'][1]:.2f}]")
m("FrPredResid", s(h["mean_resid"]))
m("FrPredResidCI", ci(h["mean_resid_ci"]))
m("FrPredMean", s(h["pred_mean"]))
m("FrObsMean", s(h["obs_mean"]))
m("FrPredVerdict", h["verdict"])
m2 = R["M2"]
m("FrMtwoRho", f"{m2['rho']:.2f}")
m("FrMtwoResid", s(m2["mean_resid"]))
m("FrMtwoResidCI", ci(m2["mean_resid_ci"]))
c1 = R["H-cov1"]
m("FrCovOneBal", s(c1["bal1_mean"]))
m("FrCovOneBalCI", ci(c1["bal1_ci"]))
m("FrCovOneCov", s(c1["cov1_mean"]))
m("FrCovOneP", p(R["tests"]["H-cov1"]["p_adj"]))
for fm, w in FM.items():
    d = R["per_fm"][fm]
    m(f"FrGapFM{w}", s(d["gap_mf"]))
    m(f"FrGapFM{w}CI", ci(d["gap_mf_ci"]))
    m(f"FrBalFM{w}", s(d["bal_mf"]))
    m(f"FrBAFM{w}", s(d["gap_ba"]))
    m(f"FrAccImbFM{w}", s(d["gap_acc_imb"]) if d["gap_acc_imb"] is not None else "n.e.")
    for t in ("H-BA", "H-acc"):
        k = f"{t}.{fm}"
        m(f"Fr{t.replace('H-', '').replace('acc', 'Acc')}PFM{w}", p(R["tests"][k]["p_adj"]))
NAMES = {"H-bal.fm1": "FrBalPFMOne", "H-bal.fm5": "FrBalPFMFive", "H-bal.order": "FrBalOrderP",
         "H-miss.cost": "FrMissCostP", "H-pred.M2": "FrMtwoP", "H-rank": "FrRankP"}
for k, nm in NAMES.items():
    m(nm, p(R["tests"][k]["p_adj"]))
r = R["H-rank"]
m("FrFlipRate", f"{100 * r['rate']:.1f}\\%")
m("FrFlipNoise", f"{100 * r['noise_rate']:.1f}\\%")
hm = R["H-miss"]
m("FrMissDiff", s(hm["mean_diff"]))
m("FrMissDiffCI", ci(hm["ci"]))
m("FrMissRhoAlone", f"{hm['rho_missshare_cov']:.2f}".replace("-", "$-$"))
m("FrMissRhoCost", f"{hm['rho_predcov_cov']:.2f}")
txt = "% generated by confirm_2026-11-08/code/make_numbers.py from results/RESULTS.json\n" + "\n".join(out) + "\n"
(BASE.parent / "confirm_numbers.tex").write_text(txt)
print(txt)
