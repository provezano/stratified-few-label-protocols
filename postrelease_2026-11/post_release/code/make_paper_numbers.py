"""Format the frozen analysis output (results/RESULTS.json) as LaTeX macros for the paper. Formatting only: no
statistic is computed here except counts read from the JSON. Not part of the frozen plan (written 2026-11-08, after
the analysis). Output: papers/p1_dmkd/exploratory/postrelease/postrelease_numbers.tex"""
import json, sys
from pathlib import Path
BASE = Path(__file__).resolve().parents[1]
OUT = BASE.parent / "exploratory" / "postrelease" / "postrelease_numbers.tex"
R = json.loads((BASE / "results" / "RESULTS.json").read_text())
FM = {"fm1": "One", "fm2": "Two", "fm3": "Three", "fm5": "Five"}
WORD = {0: "none", 1: "one", 2: "two", 3: "three", 4: "four", 5: "five", 6: "six"}
def s(x, d=3):  # signed
    v = f"{x:.{d}f}"; return ("$+$" + v) if x >= 0 else ("$-$" + v[1:])
def u(x, d=2): return f"{x:.{d}f}"
def ci(c, d=3): return f"[{s(c[0], d)}, {s(c[1], d)}]"
def p(x):
    if x < 0.001:
        e = f"{x:.1e}"; m, ex = e.split("e"); return f"${m}{{\\times}}10^{{{int(ex)}}}$"
    return f"{x:.3f}"
L = []
def m(name, val): L.append(f"\\newcommand{{\\{name}}}{{{val}}}")
T = R["tests"]
m("PRnHarvest", 40); m("PRnTables", R["n_tables"]); m("PRnDropped", 40 - R["n_tables"])
m("PRnImb", R["n_imbalanced"])
h = R["H-pred"]
m("PRrho", u(h["rho"])); m("PRrhoP", p(T["H-pred"]["p_adj"])); m("PRslope", u(h["slope"]))
m("PRslopeCI", f"[{u(h['slope_ci'][0])}, {u(h['slope_ci'][1])}]")
m("PRresid", s(h["mean_resid"])); m("PRresidCI", ci(h["mean_resid_ci"]))
m("PRpredMean", s(h["pred_mean"])); m("PRobsMean", s(h["obs_mean"])); m("PRverdict", h["verdict"])
m("PRpredPass", "yes" if T["H-pred"]["passed"] else "no")
m2 = R["M2"]
m("PRmtwoRho", u(m2["rho"])); m("PRmtwoP", p(T["H-pred.M2"]["p_adj"])); m("PRmtwoResid", s(m2["mean_resid"]))
m("PRmtwoResidCI", ci(m2["mean_resid_ci"])); m("PRmtwoPass", "yes" if T["H-pred.M2"]["passed"] else "no")
m("PRpreNineTwoRho", u(R["pre92"]["rho"])); m("PRpreNineTwoResid", s(R["pre92"]["mean_resid"]))
c = R["H-cov1"]
m("PRbalOne", s(c["bal1_mean"])); m("PRbalOneCI", ci(c["bal1_ci"])); m("PRcovOne", s(c["cov1_mean"]))
m("PRcovOnePass", "yes" if T["H-cov1"]["passed"] else "no"); m("PRcovOneP", p(T["H-cov1"]["p_adj"]))
for fm, k in FM.items():
    q = R["per_fm"][fm]
    m(f"PRgapFM{k}", s(q["gap_mf"])); m(f"PRgapFM{k}CI", ci(q["gap_mf_ci"])); m(f"PRgapFM{k}P", p(T[f"D-gap.{fm}"]["p"]))
    m(f"PRbalFM{k}", s(q["bal_mf"])); m(f"PRbaFM{k}", s(q["gap_ba"]))
    m(f"PRaccImbFM{k}", s(q["gap_acc_imb"]) if q["gap_acc_imb"] is not None else "---")
    m(f"PRaccAllFM{k}", s(q["gap_acc_all"]))
    m(f"PRbaFM{k}Pass", "yes" if T[f"H-BA.{fm}"]["passed"] else "no")
    m(f"PRbaFM{k}P", p(T[f"H-BA.{fm}"]["p_adj"]))
    m(f"PRaccFM{k}Pass", "yes" if T[f"H-acc.{fm}"]["passed"] else "no")
    m(f"PRaccFM{k}P", p(T[f"H-acc.{fm}"]["p_adj"]))
    m(f"PRcovOneFM{k}", s(c["per_fm"][fm]["bal1"]))
for t in ("H-bal.fm1", "H-bal.fm5", "H-bal.order", "H-miss.cost", "H-rank"):
    n = t.replace("H-", "").replace(".", "").replace("fm1", "One").replace("fm5", "Five").replace("order", "Order").replace("misscost", "MissCost").replace("bal", "Bal").replace("rank", "Rank")
    m(f"PR{n}Pass", "yes" if T[t]["passed"] else "no"); m(f"PR{n}P", p(T[t]["p_adj"]))
nba = sum(T[f"H-BA.{f}"]["passed"] for f in FM); nacc = sum(T[f"H-acc.{f}"]["passed"] for f in FM)
m("PRnBAPass", WORD[nba]); m("PRnAccPass", WORD[nacc])
k = R["H-rank"]
m("PRflipRate", f"{k['rate']:.2f}"); m("PRnoiseRate", f"{k['noise_rate']:.2f}"); m("PRnClear", k["clear"])
hm = R["H-miss"]
m("PRmissDiff", s(hm["mean_diff"])); m("PRmissCI", ci(hm["ci"])); m("PRmissRepro", "yes" if hm["reproducible"] else "no")
m("PRrhoMissShare", s(hm["rho_missshare_cov"], 2)); m("PRrhoPredCov", s(hm["rho_predcov_cov"], 2))
ps = [k for k, v in T.items() if v["family"] in ("primary", "secondary")]
m("PRnSecPass", sum(T[k]["passed"] for k in ps if T[k]["family"] == "secondary"))
m("PRnSec", sum(1 for k in ps if T[k]["family"] == "secondary"))
OUT.parent.mkdir(parents=True, exist_ok=True)
hdr = "% GENERATED by confirm_2026-11-08/code/make_paper_numbers.py from results/RESULTS.json (frozen analysis output)\n"
OUT.write_text(hdr + "\n".join(L) + "\n"); print(OUT, len(L), "macros")
