    d = D[fm]
    L.append(f"{nm} & {n(d['scatter'][0])} {ci(d['scatter'][1:])} & {n(d['shift'][0])} {ci(d['shift'][1:])} & {n(d['bal'][0])} {ci(d['bal'][1:])} & {d['efficiency']:.2f} & {d['lstar_mean']:.2f} \\\\\n")
